export const getCourseBySlug = (slug: string): Course | undefined => {
    const course = COURSES.find((c) => c.slug === slug);
    if (!course) return undefined;

    const templateCourse = COURSES.find((c) => c.slug === "build-digital-asset") || COURSES[0];
    return {
        ...course,
        videoThumbnail: course.videoThumbnail || templateCourse.videoThumbnail || course.thumbnail,
        videoUrl: course.videoUrl || templateCourse.videoUrl,
        sectionsCount: course.sectionsCount || 8,
        language: course.language || "English",
        lastUpdated: course.lastUpdated || "September 2024",
        certificate: course.certificate ?? true,
        description: course.description || templateCourse.description,
        keyPoints: course.keyPoints || templateCourse.keyPoints,
        sneakPeekImages: course.sneakPeekImages || templateCourse.sneakPeekImages,
        includes: course.includes || templateCourse.includes,
        modules: course.modules || templateCourse.modules,
        reviews: course.reviews || templateCourse.reviews,
        ratingDistribution: course.ratingDistribution || templateCourse.ratingDistribution,
    };
};

